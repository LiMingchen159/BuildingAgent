    "    return len(valid_index) > 1 and (valid_index.max() - valid_index.min()) >= pd.Timedelta(days=minimum_days)",
    "",
    "def _hourly_series_profile(series):",
    "    numeric = pd.to_numeric(series, errors='coerce').replace([np.inf, -np.inf], np.nan).dropna().sort_index()",
    "    if numeric.empty or not isinstance(numeric.index, pd.DatetimeIndex):",
    "        return pd.DataFrame(columns=['median', 'p10', 'p90'])",
    "    numeric.index = numeric.index.tz_localize('UTC').tz_convert(HKT) if numeric.index.tz is None else numeric.index.tz_convert(HKT)",
    "    hourly = numeric.resample('1h')",
    "    return pd.DataFrame({",
    "        'median': hourly.median(),",
    "        'p10': hourly.quantile(0.10),",
    "        'p90': hourly.quantile(0.90)",
    "    })",
    "",
    "def _small_multiples_share_y(series_values, disparity_factor=4.0):",
    "    robust_ranges = []",
    "    for values in series_values:",
    "        numeric = pd.to_numeric(values, errors='coerce').dropna()",
    "        if numeric.empty:",
    "            continue",
    "        low = float(numeric.quantile(0.05))",
    "        high = float(numeric.quantile(0.95))",
    "        robust_ranges.append((low, high))",
    "    if len(robust_ranges) < 2:",
    "        return True",
    "    spans = [max(0.0, high - low) for low, high in robust_ranges]",
    "    global_span = max(high for _low, high in robust_ranges) - min(low for low, _high in robust_ranges)",
    "    typical_span = float(np.median(spans))",
    "    if typical_span <= 1e-12:",
    "        centers = [0.5 * (low + high) for low, high in robust_ranges]",
    "        typical_level = float(np.median(np.abs(centers)))",
    "        return global_span <= max(typical_level, 1e-12)",
    "    return global_span <= max(typical_span * disparity_factor, 1e-12)",
    "",
    "def plot_series_small_multiples(data, *, title, ylabel=None, subtitle=None, sharey='auto'):",
    "    if data is None or not isinstance(data, pd.DataFrame):",
