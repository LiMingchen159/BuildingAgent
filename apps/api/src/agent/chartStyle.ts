    "    # Keep a stable header band inside the canvas so the subtitle cannot touch the first row.",
    "    fig.get_layout_engine().set(rect=(0.0, 0.0, 1.0, 0.88))",
    "    fig.patch.set_facecolor('#F8FAFC')",
    "    flat_axes = list(axes.flatten())",
    "    display_labels = _unique_series_display_labels(columns)",
    "    for index, (column, display_label) in enumerate(zip(columns, display_labels)):",
    "        ax = flat_axes[index]",
    "        style_chart_axes(ax)",
    "        color = chart_color(index)",
    "        if long_history:",
    "            profile = profiles[column]",
    "            finite = profile[['median', 'p10', 'p90']].notna().all(axis=1) if not profile.empty else pd.Series(dtype=bool)",
    "            if finite.any():",
    "                ax.fill_between(profile.index, profile['p10'].to_numpy(dtype=float), profile['p90'].to_numpy(dtype=float), where=finite.to_numpy(dtype=bool), color=color, alpha=0.16, linewidth=0)",
    "                marker_kw = {'marker': 'o', 'markersize': 3} if int(finite.sum()) <= 12 else {}",
    "                ax.plot(profile.index, profile['median'].to_numpy(dtype=float), color=color, linewidth=1.8, **marker_kw)",
    "            else:",
    "                ax.text(0.5, 0.5, 'No valid samples', transform=ax.transAxes, ha='center', va='center', color='#64748B')",
    "        else:",
    "            line = plot_series(ax, data, column, color=color, label=display_label, color_index=index)",
    "            if line is None:",
    "                ax.text(0.5, 0.5, 'No valid samples', transform=ax.transAxes, ha='center', va='center', color='#64748B')",
    "        ax.set_title(display_label, loc='left', pad=8, fontsize=11, fontweight='600', color='#0F172A')",
    "        _format_small_multiples_hkt_axis(ax, data.index)",
    "        ax.set_xlabel('')",
    "        if index // ncols < nrows - 1:",
    "            ax.tick_params(axis='x', labelbottom=False)",
    "    for ax in flat_axes[count:]:",
    "        ax.set_visible(False)",
    "    scale_note = 'shared y-scale' if use_shared_y else 'independent y-scales due to range disparity'",
    "    valid_index = data.index[~data.index.isna()] if isinstance(data.index, pd.DatetimeIndex) else data.index",
    "    date_note = ''",
    "    if len(valid_index) > 0 and isinstance(data.index, pd.DatetimeIndex):",
    "        start_hkt = valid_index.min().tz_localize('UTC').tz_convert(HKT) if valid_index.tz is None else valid_index.min().tz_convert(HKT)",
    "        end_hkt = valid_index.max().tz_localize('UTC').tz_convert(HKT) if valid_index.tz is None else valid_index.max().tz_convert(HKT)",
    "        date_note = f\"{start_hkt.strftime('%d %b')}–{end_hkt.strftime('%d %b %Y')}\"",
    "    aggregation_note = 'Hourly median with P10-P90 band · HKT' if long_history else 'Raw samples · HKT'",
    "    chart_subtitle = ' · '.join(part for part in [subtitle, aggregation_note, date_note, scale_note] if part)",
    "    fig.suptitle(title, x=0.02, y=0.985, ha='left', fontsize=16, fontweight='600', color='#0F172A')",
    "    fig.text(0.02, 0.94, chart_subtitle, ha='left', va='top', fontsize=10, color='#64748B')",
    "    fig.supxlabel('Time (HKT)', fontsize=11, color='#64748B')",
    "    if ylabel:",
    "        fig.supylabel(ylabel, fontsize=11, color='#64748B')",
    "    return fig, axes",
    "",
