    "def plot_status_step(ax, data, col=None, *, color='orange', alpha=0.25, label=None, **kwargs):",
    "    # Discrete status only (Run_Status, S, etc.) — step fill, not for analog signals.",
    "    if isinstance(data, pd.DataFrame):",
