/** Detect chart intent without save_chart output — for execute_code sanity check. */
export function chartSanityViolation(userCode: string, newPngCount: number): string | null {
  const trimmed = userCode.trim();
  if (!trimmed) {
    return null;
  }
  const chartIntent =
    /\bnew_figure\s*\(|\bplot_series\s*\(|\bplot_timeseries_default\s*\(|\bplot_series_small_multiples\s*\(|\bplt\.subplots\s*\(|\bplt\.plot\s*\(|\b\.plot\s*\(|\baxes\[\d+\]\.plot\s*\(/i.test(trimmed);
  if (/\bsave_chart\s*\(/i.test(trimmed) || newPngCount > 0) {
    return null;
  }
  const debugOnly =
    /\bprint\s*\(/i.test(trimmed)
    && /\b(build_combined_frame|load_all_series|\.columns|\.shape|data_coverage)\b/i.test(trimmed);
  if (debugOnly && !chartIntent) {
    return "Debug-only execute_code (print columns/shape/coverage) is not allowed after data tools. One pass ending in save_chart().";
  }
  if (chartIntent) {
    return "Chart code detected but save_chart() was not called and no PNG was generated. End chart scripts with save_chart(fig, 'name.png').";
  }
  return null;
}

